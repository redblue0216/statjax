### Basic package
import pytest
### Algorithm package
import jax
import jax.numpy as jnp
from jax.numpy.linalg import lstsq
### Project Package - Algorithm Components
from statjax.regression import SVDRidgeComponent



####### Global Parameters ##########################################################################
####################################################################################################



### Enable float64 precision before any JAX array creation
jax.config.update("jax_enable_x64",True)

### Sample size and feature dimension of the simulated dataset
N_TRAIN,P_DIM = 200,60
### Number of collinear columns (the last N_COLLINEAR columns are linear combinations of the previous columns plus tiny perturbations)
N_COLLINEAR = 20
### Number of test set samples
N_TEST = 10
### Gaussian noise scale, controls the size of data perturbation
NOISE_SCALE = 4.0
### L2 regularization coefficient
LAM = 1.0
### Machine precision threshold: the deviation between the SVD solution and the closed-form solution should be at the float64 machine precision level
MACHINE_PRECISION_TOL = 1e-8



####### Auxiliary Functions ########################################################################
####################################################################################################



def generate_ridge_data(n,p,n_collinear,noise_scale=NOISE_SCALE):
    '''Method Function:

        Define a reproducible and verifiable ridge regression simulated dataset generation function, the main function is to construct a near rank-deficient design matrix with multicollinearity and observation labels with preset true values, the main technical fixed random seeds

    :parameters:
        - n (int) - Total number of samples
        - p (int) - Feature dimension
        - n_collinear (int) - Number of collinear columns, the last n_collinear columns are linear combinations of the previous columns plus tiny perturbations
        - noise_scale (float) - Gaussian noise scale, controls the size of data perturbation

    :return:
        - A (jnp.ndarray) - (n,p) Near rank-deficient design matrix with multicollinearity
        - b (jnp.ndarray) - (n,) Observation label vector
        - w_true (jnp.ndarray) - (p,) Preset true regression coefficients (for accuracy verification)
    '''

    ### Fix random seeds to ensure that the generated data is completely consistent every time, achieving absolute reproducibility
    keys = jax.random.split(jax.random.PRNGKey(0),5)

    ### Generate independent base feature columns subject to Gaussian distribution
    A_base = jax.random.normal(keys[0],(n,p - n_collinear),dtype=jnp.float64)

    ### Construct the last n_collinear columns as linear combinations of the base columns plus tiny perturbations, manufacturing a near rank-deficient design matrix with multicollinearity
    mixing_matrix = jax.random.normal(keys[1],(p - n_collinear,n_collinear),dtype=jnp.float64)
    A_col = A_base @ mixing_matrix + 1e-6 * jax.random.normal(keys[2],(n,n_collinear),dtype=jnp.float64)
    A = jnp.concatenate([A_base,A_col],axis=1)

    ### Preset true regression weights (true values, used for subsequent quantification of fitting errors)
    w_true = jax.random.normal(keys[3],(p,),dtype=jnp.float64)

    ### Construct observation labels with Gaussian noise: b = A·w_true + noise
    noise = noise_scale * jax.random.normal(keys[4],(n,),dtype=jnp.float64)
    b = A @ w_true + noise

    return A,b,w_true



####### Test Fixtures ##############################################################################
####################################################################################################



@pytest.fixture(scope="module")
def trained_component():
    '''Method Function:

        Define a module-level test fixture, the main function is to provide a trained SVDRidgeComponent instance and the simulated dataset for all test cases to share

    :parameters:
        nothing

    :return:
        - data (dict) - Dictionary containing the trained component instance, the simulated dataset, and the training results
    '''

    ### Generate the training dataset with multicollinearity
    A_train,b_train,w_true = generate_ridge_data(N_TRAIN,P_DIM,N_COLLINEAR)
    ### Train the ridge regression model
    component = SVDRidgeComponent(lam=LAM)
    w_hat,metrics = component.train(A=A_train,b=b_train)

    return {
        "component": component,
        "A_train": A_train,
        "b_train": b_train,
        "w_true": w_true,
        "w_hat": w_hat,
        "metrics": metrics
    }



####### Test Classes ###############################################################################
####################################################################################################



class TestSVDRidgeComponent:
    '''Class Introduction:

        This is a unit test class of the SVDRidgeComponent component, the main function is to test the three unified interfaces of train, reasoning, and _info
    '''


    def test_train_output_shape(self,trained_component):
        '''Method Function:

            Test whether the shape and precision of the trained ridge regression coefficients meet expectations
        '''

        w_hat = trained_component["w_hat"]
        assert w_hat.shape == (P_DIM,)
        assert w_hat.dtype == jnp.float64


    def test_train_residual(self,trained_component):
        '''Method Function:

            Test whether the fitting residual 2-norm of the training set is at the noise scale level
        '''

        residual_norm = trained_component["metrics"]["residual_norm"]
        ### The residual should be of the same magnitude as noise_scale * sqrt(n), with a loose upper bound
        assert residual_norm < 10 * NOISE_SCALE * jnp.sqrt(N_TRAIN)


    def test_diff_with_closed_form(self,trained_component):
        '''Method Function:

            Test whether the deviation between the SVD solution and the closed-form solution is at the float64 machine precision level, which is the core criterion for the correctness of the algorithm
        '''

        diff_with_closed_form = trained_component["metrics"]["diff_with_closed_form"]
        assert diff_with_closed_form < MACHINE_PRECISION_TOL


    def test_coef_shrinkage(self,trained_component):
        '''Method Function:

            Test whether the L2 regularization shrinkage effect is significant under multicollinearity: the ridge coefficient norm should be orders of magnitude smaller than the exploding OLS (lambda=0) coefficient norm
        '''

        A_train = trained_component["A_train"]
        b_train = trained_component["b_train"]

        ### Train the degenerated OLS solution (lambda=0) on the same data for contrast
        ols_component = SVDRidgeComponent(lam=0.0)
        _,ols_metrics = ols_component.train(A=A_train,b=b_train)

        ridge_coef_norm = trained_component["metrics"]["coef_norm"]
        ols_coef_norm = ols_metrics["coef_norm"]
        ### Under strong multicollinearity, the OLS coefficient norm explodes, while ridge shrinks it by orders of magnitude
        assert ridge_coef_norm < ols_coef_norm * 1e-3


    def test_lam_zero_equals_ols(self,trained_component):
        '''Method Function:

            Test whether the SVD solution degenerates to the OLS solution when lambda=0: the relative deviation from the official lstsq benchmark should be at the machine precision level
        '''

        A_train = trained_component["A_train"]
        b_train = trained_component["b_train"]

        ### Train the degenerated OLS solution (lambda=0)
        ols_component = SVDRidgeComponent(lam=0.0)
        w_ols,_ = ols_component.train(A=A_train,b=b_train)

        ### Compare with the JAX official lstsq benchmark algorithm (relative deviation, since the OLS coefficient norm explodes under multicollinearity)
        w_lstsq,_,_,_ = lstsq(A_train,b_train,rcond=None)
        relative_diff = jnp.linalg.norm(w_ols - w_lstsq) / jnp.linalg.norm(w_lstsq)
        assert relative_diff < MACHINE_PRECISION_TOL


    def test_reasoning_predict(self,trained_component):
        '''Method Function:

            Test whether the error norm between the batch prediction of the reasoning method and the noise-free true labels of the test set is within tolerance
        '''

        ### Generate the test set feature matrix
        key_test = jax.random.PRNGKey(7)
        A_test = jax.random.normal(key_test,(N_TEST,P_DIM),dtype=jnp.float64)
        ### Calculate the true labels of the test set (no additional noise, for accurate comparison)
        y_test_true = A_test @ trained_component["w_true"]

        ### Batch prediction by the model
        y_pred = trained_component["component"].reasoning(A_test=A_test)

        assert y_pred.shape == (N_TEST,)
        test_pred_error = jnp.linalg.norm(y_pred - y_test_true)
        assert test_pred_error < 10 * NOISE_SCALE * jnp.sqrt(N_TEST)


    def test_reasoning_before_train(self):
        '''Method Function:

            Test whether calling the reasoning method before training throws the expected exception
        '''

        component = SVDRidgeComponent(lam=LAM)
        A_test = jnp.ones((N_TEST,P_DIM),dtype=jnp.float64)
        with pytest.raises(RuntimeError,match="has not been trained yet"):
            component.reasoning(A_test=A_test)


    def test_info(self):
        '''Method Function:

            Test whether the _info method returns a non-empty string
        '''

        info = SVDRidgeComponent(lam=LAM)._info()
        assert isinstance(info,str)
        assert len(info) > 0



