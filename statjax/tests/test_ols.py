### Basic package
import pytest
### Algorithm package
import jax
import jax.numpy as jnp
### Project Package - Algorithm Components
from statjax.regression import HouseholderOLSComponent



####### Global Parameters ##########################################################################
####################################################################################################



### Enable float64 precision before any JAX array creation
jax.config.update("jax_enable_x64",True)

### Sample size and feature dimension of the simulated dataset
N_TRAIN,P_DIM = 100,5
### Number of test set samples
N_TEST = 10
### Gaussian noise scale, controls the size of data perturbation
NOISE_SCALE = 0.05
### Machine precision threshold: the deviation between the QR solution and the official lstsq solution should be at the 1e-12~1e-16 level
MACHINE_PRECISION_TOL = 1e-10



####### Auxiliary Functions ########################################################################
####################################################################################################



def generate_ols_data(n,p,noise_scale=NOISE_SCALE):
    '''Method Function:

        Define a reproducible and verifiable OLS simulated dataset generation function, the main function is to construct a column full rank design matrix and observation labels with preset true values, the main technical dual fixed random seeds

    :parameters:
        - n (int) - Total number of samples
        - p (int) - Feature dimension
        - noise_scale (float) - Gaussian noise scale, controls the size of data perturbation

    :return:
        - A (jnp.ndarray) - (n,p) Column full rank design matrix
        - b (jnp.ndarray) - (n,) Observation label vector
        - x_true (jnp.ndarray) - (p,) Preset true regression coefficients (for accuracy verification)
    '''

    ### Fix dual random seeds to ensure that the generated data is completely consistent every time, achieving absolute reproducibility
    key_A = jax.random.PRNGKey(0)
    key_noise = jax.random.PRNGKey(1)

    ### Preset true regression weights (true values, used for subsequent quantification of fitting errors)
    x_true = jnp.array([1.2,-2.1,0.7,3.3,-1.5],dtype=jnp.float64)[:p]

    ### Generate a column full rank design matrix subject to Gaussian distribution
    A = jax.random.normal(key_A,(n,p),dtype=jnp.float64)

    ### Generate tiny Gaussian noise to simulate measurement errors in real observation scenarios
    noise = noise_scale * jax.random.normal(key_noise,(n,),dtype=jnp.float64)

    ### Construct standard OLS observation labels: b = A·x_true + noise
    b = A @ x_true + noise

    return A,b,x_true



####### Test Fixtures ##############################################################################
