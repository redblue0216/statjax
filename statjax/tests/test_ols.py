@pytest.fixture(scope="module")
def trained_component():
    '''Method Function:

        Define a module-level test fixture, the main function is to provide a trained HouseholderOLSComponent instance and the simulated dataset for all test cases to share

    :parameters:
        nothing

    :return:
        - data (dict) - Dictionary containing the trained component instance, the simulated dataset, and the training results
    '''

    ### Generate the training dataset
    A_train,b_train,x_true = generate_ols_data(N_TRAIN,P_DIM)
    ### Train the OLS model
    component = HouseholderOLSComponent()
    x_hat,metrics = component.train(A=A_train,b=b_train)

    return {
        "component": component,
        "A_train": A_train,
        "b_train": b_train,
        "x_true": x_true,
        "x_hat": x_hat,
        "metrics": metrics
    }



####### Test Classes ###############################################################################
####################################################################################################



class TestHouseholderOLSComponent:
    '''Class Introduction:

        This is a unit test class of the HouseholderOLSComponent component, the main function is to test the three unified interfaces of train, reasoning, and _info
    '''


    def test_train_output_shape(self,trained_component):
        '''Method Function:

            Test whether the shape and precision of the trained regression coefficients meet expectations
        '''

        x_hat = trained_component["x_hat"]
        assert x_hat.shape == (P_DIM,)
        assert x_hat.dtype == jnp.float64


    def test_train_residual(self,trained_component):
        '''Method Function:

            Test whether the fitting residual 2-norm of the training set is at the noise scale level
        '''

        residual_norm = trained_component["metrics"]["residual_norm"]
        ### The residual should be of the same magnitude as noise_scale * sqrt(n), with a loose upper bound
        assert residual_norm < 10 * NOISE_SCALE * jnp.sqrt(N_TRAIN)


    def test_diff_with_lstsq(self,trained_component):
        '''Method Function:

            Test whether the deviation between the QR solution and the official lstsq solution is at the machine precision level, which is the core criterion for the correctness of the algorithm
        '''

        diff_with_lstsq = trained_component["metrics"]["diff_with_lstsq"]
        assert diff_with_lstsq < MACHINE_PRECISION_TOL


    def test_param_close_to_true(self,trained_component):
        '''Method Function:

            Test whether the error norm between the trained regression coefficients and the preset true values is within tolerance
        '''

        param_error = jnp.linalg.norm(trained_component["x_hat"] - trained_component["x_true"])
        assert param_error < 10 * NOISE_SCALE


    def test_reasoning_predict(self,trained_component):
        '''Method Function:

            Test whether the error norm between the batch prediction of the reasoning method and the noise-free true labels of the test set is within tolerance
        '''

        ### Generate the test set feature matrix
        key_test = jax.random.PRNGKey(2)
        A_test = jax.random.normal(key_test,(N_TEST,P_DIM),dtype=jnp.float64)
        ### Calculate the true labels of the test set (no additional noise, for accurate comparison)
        y_test_true = A_test @ trained_component["x_true"]

        ### Batch prediction by the model
        y_pred = trained_component["component"].reasoning(A_test=A_test)

        assert y_pred.shape == (N_TEST,)
        test_pred_error = jnp.linalg.norm(y_pred - y_test_true)
        assert test_pred_error < 10 * NOISE_SCALE * jnp.sqrt(N_TEST)


    def test_reasoning_before_train(self):
        '''Method Function:

            Test whether calling the reasoning method before training throws the expected exception
        '''

        component = HouseholderOLSComponent()
        A_test = jnp.ones((N_TEST,P_DIM),dtype=jnp.float64)
        with pytest.raises(RuntimeError,match="has not been trained yet"):
            component.reasoning(A_test=A_test)


    def test_info(self):
        '''Method Function:

            Test whether the _info method returns a non-empty string
        '''

        info = HouseholderOLSComponent()._info()
        assert isinstance(info,str)
        assert len(info) > 0



