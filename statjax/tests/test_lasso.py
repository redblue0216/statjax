### Basic package
import pytest
### Algorithm package
import jax
import jax.numpy as jnp
from jax.numpy.linalg import lstsq
### Project Package - Algorithm Components
from statjax.regression import CDLassoComponent



####### Global Parameters ##########################################################################
####################################################################################################



### Enable float64 precision before any JAX array creation
jax.config.update("jax_enable_x64",True)

### Sample size and feature dimension of the simulated dataset
N_TRAIN,P_DIM = 200,30
### Number of non-zero true coefficients (only the first N_NONZERO coefficients are non-zero)
N_NONZERO = 5
### Number of test set samples
N_TEST = 10
### Gaussian noise scale, controls the size of data perturbation
NOISE_SCALE = 0.1
### L1 regularization coefficient
LAM = 0.1
### KKT optimality tolerance: the maximum violation of the KKT optimality condition should approach 0 when ideally converged under float64
KKT_TOL = 1e-6
### Machine precision threshold: when lambda=0 the coordinate descent solution degenerates to OLS, and the deviation from the official lstsq benchmark with an explicit intercept column should be at the machine precision level
MACHINE_PRECISION_TOL = 1e-10



####### Auxiliary Functions ########################################################################
####################################################################################################



def generate_lasso_data(n,p,n_nonzero,noise_scale=NOISE_SCALE):
    '''Method Function:

        Define a reproducible and verifiable LASSO simulated dataset generation function, the main function is to construct a design matrix and observation labels with sparse preset true values (only the first n_nonzero coefficients are non-zero), the main technical dual fixed random seeds

    :parameters:
        - n (int) - Total number of samples
        - p (int) - Feature dimension
        - n_nonzero (int) - Number of non-zero true coefficients, only the first n_nonzero coefficients are non-zero
        - noise_scale (float) - Gaussian noise scale, controls the size of data perturbation

    :return:
        - A (jnp.ndarray) - (n,p) Design matrix
        - b (jnp.ndarray) - (n,) Observation label vector
        - w_true (jnp.ndarray) - (p,) Preset sparse true regression coefficients (for accuracy and sparsity verification)
    '''

    ### Fix dual random seeds to ensure that the generated data is completely consistent every time, achieving absolute reproducibility
    key_A = jax.random.PRNGKey(0)
    key_noise = jax.random.PRNGKey(1)

    ### Preset sparse true regression weights (only the first n_nonzero coefficients are non-zero, used for subsequent quantification of fitting errors and sparsity recovery verification)
    w_true = jnp.zeros(p,dtype=jnp.float64)
    w_true = w_true.at[:n_nonzero].set(jnp.array([1.2,-0.8,0.6,-1.1,0.9],dtype=jnp.float64)[:n_nonzero])

    ### Generate a design matrix subject to Gaussian distribution
    A = jax.random.normal(key_A,(n,p),dtype=jnp.float64)

    ### Generate tiny Gaussian noise to simulate measurement errors in real observation scenarios
    noise = noise_scale * jax.random.normal(key_noise,(n,),dtype=jnp.float64)

    ### Construct standard observation labels: b = A·w_true + noise
    b = A @ w_true + noise

    return A,b,w_true



####### Test Fixtures ##############################################################################
####################################################################################################



@pytest.fixture(scope="module")
def trained_component():
    '''Method Function:

        Define a module-level test fixture, the main function is to provide a trained CDLassoComponent instance and the simulated dataset for all test cases to share

    :parameters:
        nothing

    :return:
        - data (dict) - Dictionary containing the trained component instance, the simulated dataset, and the training results
    '''

    ### Generate the training dataset with sparse true coefficients
    A_train,b_train,w_true = generate_lasso_data(N_TRAIN,P_DIM,N_NONZERO)
    ### Train the LASSO model
    component = CDLassoComponent(lam=LAM)
    w_hat,metrics = component.train(A=A_train,b=b_train)

    return {
        "component": component,
        "A_train": A_train,
        "b_train": b_train,
        "w_true": w_true,
        "w_hat": w_hat,
        "metrics": metrics
    }



####### Test Classes ###############################################################################
####################################################################################################



class TestCDLassoComponent:
    '''Class Introduction:

        This is a unit test class of the CDLassoComponent component, the main function is to test the three unified interfaces of train, reasoning, and _info
    '''


    def test_train_output_shape(self,trained_component):
        '''Method Function:

            Test whether the shape and precision of the trained LASSO regression coefficients meet expectations
        '''

        w_hat = trained_component["w_hat"]
        assert w_hat.shape == (P_DIM,)
        assert w_hat.dtype == jnp.float64


    def test_train_residual(self,trained_component):
        '''Method Function:

            Test whether the fitting residual 2-norm of the training set is at the noise scale level
        '''

        residual_norm = trained_component["metrics"]["residual_norm"]
        ### The residual should be of the same magnitude as noise_scale * sqrt(n), with a loose upper bound
        assert residual_norm < 10 * NOISE_SCALE * jnp.sqrt(N_TRAIN)


    def test_kkt_violation(self,trained_component):
        '''Method Function:

            Test whether the maximum violation of the KKT optimality condition approaches 0 under float64, which is the core criterion for the correctness of the algorithm (JAX native verification, replacing sklearn comparison)
        '''

        kkt_violation = trained_component["metrics"]["kkt_violation"]
        assert kkt_violation < KKT_TOL


    def test_sparsity_recovery(self,trained_component):
        '''Method Function:

            Test whether the L1 regularization sparsity effect is significant: the first N_NONZERO true non-zero coefficients are accurately recovered, and the remaining noise coefficients are compressed to near 0 (feature selection effect)
        '''

        w_hat = trained_component["w_hat"]
        w_true = trained_component["w_true"]

        ### The true non-zero coefficients should be accurately recovered within tolerance
        nonzero_error = jnp.linalg.norm(w_hat[:N_NONZERO] - w_true[:N_NONZERO])
        assert nonzero_error < 10 * NOISE_SCALE

        ### The noise coefficients should be compressed to near 0 by the soft thresholding operator
        zero_coef_max = jnp.max(jnp.abs(w_hat[N_NONZERO:]))
        assert zero_coef_max < NOISE_SCALE


    def test_lam_large_all_zero(self):
        '''Method Function:

            Test whether all coefficients are compressed to 0 when lambda is large enough (the extreme behavior of the soft thresholding operator)
        '''

        A_train,b_train,_ = generate_lasso_data(N_TRAIN,P_DIM,N_NONZERO)

        ### Train with an extremely large lambda
        component = CDLassoComponent(lam=1e6)
        w_hat,metrics = component.train(A=A_train,b=b_train)

        assert metrics["n_nonzero"] == 0
        assert float(jnp.max(jnp.abs(w_hat))) == 0.0


    def test_lam_zero_equals_ols(self,trained_component):
        '''Method Function:

            Test whether the coordinate descent solution degenerates to the OLS solution when lambda=0: the deviation from the official lstsq benchmark with an explicit intercept column should be at the machine precision level (the component separates the intercept from the L1 penalty, so the benchmark must also include the intercept for an apples-to-apples comparison)
        '''

        A_train = trained_component["A_train"]
        b_train = trained_component["b_train"]

        ### Train the degenerated OLS solution (lambda=0)
        ols_component = CDLassoComponent(lam=0.0)
        w_ols,_ = ols_component.train(A=A_train,b=b_train)

        ### Compare with the JAX official lstsq benchmark algorithm augmented with an explicit intercept column
        A_ext = jnp.concatenate([jnp.ones((A_train.shape[0],1),dtype=A_train.dtype),A_train],axis=1)
        sol,_,_,_ = lstsq(A_ext,b_train,rcond=None)
        diff_w = jnp.linalg.norm(w_ols - sol[1:])
        diff_intercept = jnp.abs(ols_component.intercept - sol[0])
        assert diff_w < MACHINE_PRECISION_TOL
        assert diff_intercept < MACHINE_PRECISION_TOL


    def test_reasoning_predict(self,trained_component):
        '''Method Function:

            Test whether the error norm between the batch prediction of the reasoning method and the noise-free true labels of the test set is within tolerance
        '''

        ### Generate the test set feature matrix
        key_test = jax.random.PRNGKey(7)
        A_test = jax.random.normal(key_test,(N_TEST,P_DIM),dtype=jnp.float64)
        ### Calculate the true labels of the test set (no additional noise, for accurate comparison)
        y_test_true = A_test @ trained_component["w_true"]

        ### Batch prediction by the model (intercept is automatically added back)
        y_pred = trained_component["component"].reasoning(A_test=A_test)

        assert y_pred.shape == (N_TEST,)
        test_pred_error = jnp.linalg.norm(y_pred - y_test_true)
        assert test_pred_error < 10 * NOISE_SCALE * jnp.sqrt(N_TEST)


    def test_reasoning_before_train(self):
        '''Method Function:

            Test whether calling the reasoning method before training throws the expected exception
        '''

        component = CDLassoComponent(lam=LAM)
        A_test = jnp.ones((N_TEST,P_DIM),dtype=jnp.float64)
        with pytest.raises(RuntimeError,match="has not been trained yet"):
            component.reasoning(A_test=A_test)


    def test_info(self):
        '''Method Function:

            Test whether the _info method returns a non-empty string
        '''

        info = CDLassoComponent(lam=LAM)._info()
        assert isinstance(info,str)
        assert len(info) > 0



